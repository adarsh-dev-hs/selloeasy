#!/usr/bin/env node
// Merges deploy-time values into the current `selloeasy/<env>/app` JSON secret (read from stdin) and prints the result.
//
// - Provider API keys: taken from the env file when set; the selected LLM_PROVIDER's key is required.
// - JWT_ACCESS_SECRET / JWT_REFRESH_SECRET: env file value if it is a real secret (>= 32 chars, not a placeholder);
//   otherwise the existing value is kept; otherwise the openssl-generated GENERATED_* value is used.
// - SUPERADMIN_PASSWORD: env file value unless it is the local default (Admin@123); otherwise keep / generate.
// - Every other existing key (e.g. ORIGIN_VERIFY_TOKEN generated by CloudFormation) is preserved.
// Writes a short, secret-free summary to stderr.
import { readFileSync } from 'node:fs';

const current = (() => {
  const raw = readFileSync(0, 'utf8').trim();
  if (!raw || raw === 'None') return {};
  return JSON.parse(raw);
})();
const env = process.env;
const summary = [];

const isPlaceholder = (v) => !v || v.length < 32 || /^(change-me|local-dev)/.test(v);
const pick = (key, fromEnv, generated, invalid) => {
  if (fromEnv && !invalid(fromEnv)) {
    summary.push(`${key}: ${current[key] === fromEnv ? 'unchanged' : 'from env file'}`);
    return fromEnv;
  }
  if (current[key]) {
    summary.push(`${key}: kept existing`);
    return current[key];
  }
  if (!generated) throw new Error(`No value for ${key}`);
  summary.push(`${key}: generated`);
  return generated;
};

const next = { ...current };
// Provider API keys (plan2 §10): the selected LLM_PROVIDER's key is required; others are copied when present.
const PROVIDER_KEYS = { openrouter: 'OPENROUTER_API_KEY', openai: 'OPENAI_API_KEY', anthropic: 'ANTHROPIC_API_KEY' };
const selected = PROVIDER_KEYS[env.LLM_PROVIDER || 'openrouter'];
if (!selected) throw new Error(`Unknown LLM_PROVIDER ${env.LLM_PROVIDER}`);
if (!env[selected] && !current[selected]) throw new Error(`${selected} is required for LLM_PROVIDER=${env.LLM_PROVIDER || 'openrouter'}`);
for (const key of Object.values(PROVIDER_KEYS)) {
  if (!env[key]) continue;
  summary.push(`${key}: ${current[key] === env[key] ? 'unchanged' : 'from env file'}`);
  next[key] = env[key];
}
next.JWT_ACCESS_SECRET = pick(
  'JWT_ACCESS_SECRET',
  env.JWT_ACCESS_SECRET,
  env.GENERATED_JWT_ACCESS_SECRET,
  isPlaceholder,
);
next.JWT_REFRESH_SECRET = pick(
  'JWT_REFRESH_SECRET',
  env.JWT_REFRESH_SECRET,
  env.GENERATED_JWT_REFRESH_SECRET,
  isPlaceholder,
);
next.SUPERADMIN_PASSWORD = pick(
  'SUPERADMIN_PASSWORD',
  env.SUPERADMIN_PASSWORD,
  env.GENERATED_SUPERADMIN_PASSWORD,
  (v) => !v || v === 'Admin@123' || v.length < 10,
);

process.stderr.write(summary.map((s) => `    ${s}`).join('\n') + '\n');
process.stdout.write(JSON.stringify(next));
